"""Build the offline booth syllable subset. Build-only: pip install cmudict==1.1.3."""
import json
import re
from pathlib import Path

import cmudict

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'daily_flyer/themes/pocket_gridiron_assets'
SOURCES = ['booth-lines.js', 'booth-extras.js', 'sideline.js', 'special-teams.js', 'broadcast.js', 'match.js',
           'teams.js', 'roster.js', 'rosters.json', 'syllables.js']
words = set('area idea radio quiet poem science create dial Michaels Madden strengths thought'.lower().split())
words.update("doesn't didn't couldn't shouldn't wouldn't isn't wasn't aren't weren't hasn't hadn't haven't mustn't needn't won't can't don't I've we're you'd he'll it's that's there's they're we'll you're I'll I've I'd we've you've she's he's player player's".lower().split())
for name in SOURCES:
    text = (ASSETS / name).read_text().replace('’', "'")
    words.update(w.lower() for w in re.findall(r"[A-Za-z]+(?:'[A-Za-z]+)*", text))
dictionary = cmudict.dict()
subset = {w: ''.join(p[-1] for p in dictionary[w][0] if p[-1].isdigit())
          for w in sorted(words) if w in dictionary}
license_text = Path(cmudict.__file__).parent.joinpath('data/LICENSE').read_text()
(ASSETS / 'booth-pronunciations.js').write_text(
    '// Generated by scripts/build_booth_pronunciations.py with cmudict==1.1.3.\n'
    '// https://github.com/cmusphinx/cmudict — syllable stress only; no speech audio.\n'
    '/*\n' + license_text + '\n*/\n'
    'export const PRONUNCIATIONS=Object.freeze(' + json.dumps(subset, separators=(',', ':')) + ');\n')
print(f'Wrote {len(subset)} pronunciations.')
