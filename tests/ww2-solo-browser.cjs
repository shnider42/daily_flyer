 await page.locator('#playbackPanel').waitFor({state:'visible'});
 await page.locator('#pausePlayback').click();
 assert.equal(await page.locator('#map').isVisible(),false);
 assert.equal(await page.locator('#playbackMap').isVisible(),true);
 assert.equal(await page.locator('#orders').evaluate(e=>e.inert),true);
 const committed=await page.evaluate(()=>state.revision),turnPosts=posts;
