  function setLocale(value) {
    locale = value === 'de-AT' ? 'de-AT' : 'en-US';
    return locale;
  }
  function getLocale() { return locale; }
  function translate(value) {
    if (Object.prototype.hasOwnProperty.call(copy, value)) return copy[value];
    const sourceLabels = root.HuddleContentAT && root.HuddleContentAT.sourceLabels;
    if (sourceLabels && Object.prototype.hasOwnProperty.call(sourceLabels, value)) return sourceLabels[value];
    for (const [pattern, replace] of patterns) {
      const found = value.match(pattern);
      if (found) return replace(...found);
    }
    // Decorative action marks are independent of the translatable label.
    const decorated = value.match(/^(.*?)\s*([↗✓])$/u);
    if (decorated) {
      const translated = translate(decorated[1].trimEnd());
      if (translated !== decorated[1].trimEnd()) return translated + ' ' + decorated[2];
    }
    return value;
  }
  function text(value) {
    const input = String(value == null ? '' : value);
    if (locale !== 'de-AT' || !input.trim()) return input;
    const content = input.trim();
    const start = input.indexOf(content);
    return input.slice(0, start) + translate(content) + input.slice(start + content.length);
  }
  function excluded(element, forText) {
    return !element || !!element.closest(forText
      ? 'script,style,textarea,code,pre,[data-original-language]'
      : 'script,style,code,pre,[data-original-language]');
  }
  function apply(target) {
    const document = target && target.ownerDocument || root.document;
    if (!document) return;
    target = target || document.body;
    if (!target) return;
    const walker = document.createTreeWalker(target, 4 /* SHOW_TEXT */);
    let node;
    while ((node = walker.nextNode())) {
      if (excluded(node.parentElement, true)) continue;
      const previous = originals.get(node);
      const source = previous && node.nodeValue === previous.output ? previous.source : node.nodeValue;
      const output = text(source);
      if (node.nodeValue !== output) node.nodeValue = output;
      originals.set(node, { source, output });
    }
    const elements = target.nodeType === 1
      ? [target, ...target.querySelectorAll('[aria-label],[title],[placeholder]')]
      : [...target.querySelectorAll('[aria-label],[title],[placeholder]')];
    for (const element of elements) {
      if (excluded(element, false)) continue;
      let previous = attributes.get(element);
      if (!previous) { previous = {}; attributes.set(element, previous); }
      for (const name of ['aria-label', 'title', 'placeholder']) {
        if (!element.hasAttribute(name)) { delete previous[name]; continue; }
        const current = element.getAttribute(name), saved = previous[name];
        const source = saved && current === saved.output ? saved.source : current;
        const output = text(source);
        if (current !== output) element.setAttribute(name, output);
        previous[name] = { source, output };
      }
    }
  }
